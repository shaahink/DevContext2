// P2.1 evidence generator. Pure ASCII on purpose (PS 5.1 reads unmarked UTF-8 as cp1252).
//
//   node eval/agent-probe/p2-summary.mjs --repo eShop [--out results/p2.1-pilot.md]
//
// This file DESCRIBES the pilot; it does not grade it (that is A1.1) and it does not decide the
// verdict (that is R1.1). It reports exactly the four numbers DESIGN section 10 says the pilot
// exists to produce - does mcp_call_share clear 0.2, does total_cost_usd populate, do the arm
// isolation assertions hold, is between-rep variance small enough for n=5 to resolve a 20% effect
// - plus the coverage, the per-arm censoring rate DESIGN 6.6 requires, and the count of
// infrastructure attempts that were quarantined rather than recorded.
//
// It computes nothing it cannot show its working for, and it never drops a row.

import { readFileSync, existsSync, writeFileSync } from "fs";
import { join, dirname, resolve } from "path";
import { fileURLToPath } from "url";

const HERE = dirname(fileURLToPath(import.meta.url));
const RESULTS = join(HERE, "results");
const ARMS = ["G", "M", "B"];
const REPS = [1, 2, 3];

const argv = process.argv.slice(2);
const argOf = (n, d) => { const i = argv.indexOf(`--${n}`); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };
const REPO = argOf("repo", "eShop");
const OUT = resolve(HERE, argOf("out", "results/p2.1-pilot.md"));

function readJsonl(p) {
  if (!existsSync(p)) return [];
  return readFileSync(p, "utf8").split("\n").filter((l) => l.trim()).map((l) => JSON.parse(l));
}

// Median of a numeric list. Even-length takes the mean of the two middle values, which is the
// ordinary convention; every median in this report is over a small n so it is worth being exact.
function median(xs) {
  const a = xs.filter((x) => typeof x === "number" && Number.isFinite(x)).slice().sort((x, y) => x - y);
  if (!a.length) return null;
  const m = a.length >> 1;
  return a.length % 2 ? a[m] : (a[m - 1] + a[m]) / 2;
}
const fmt = (x, d = 4) => (x == null ? "-" : Number(x).toFixed(d));

// mcp_call_share, per DESIGN 3.1's manipulation check: of the tool calls that ACTUALLY EXECUTED
// (a denied call is an attempt, not an action), what fraction were mcp__ calls.
function mcpShare(row) {
  const ex = row.toolCallsExecuted || [];
  if (!ex.length) return null;
  return ex.filter((c) => String(c).startsWith("mcp__")).length / ex.length;
}

const runs = readJsonl(join(RESULTS, "runs.jsonl")).filter((r) => r.repo === REPO);
const infra = readJsonl(join(RESULTS, "infra-failures.jsonl")).filter((r) => r.repo === REPO);
const questions = JSON.parse(readFileSync(join(HERE, "questions", `${REPO}.json`), "utf8"));
const QIDS = questions.questions.map((q) => q.id);
const CLASS_OF = Object.fromEntries(questions.questions.map((q) => [q.id, q.class]));

// ---- coverage ---------------------------------------------------------------
const key = (q, a, r) => `${q}|${a}|${r}`;
const have = new Map();
for (const r of runs) have.set(key(r.questionId, r.arm, r.rep), r);
const expected = [];
for (const q of QIDS) for (const a of ARMS) for (const rep of REPS) expected.push(key(q, a, rep));
const missing = expected.filter((k) => !have.has(k));
const dupes = expected.filter((k) => runs.filter((r) => key(r.questionId, r.arm, r.rep) === k).length > 1);

const L = [];
const P = (s = "") => L.push(s);

P(`# P2.1 - eShop pilot, 6 questions x 3 arms x 3 reps`);
P();
P(`Generated by \`eval/agent-probe/p2-summary.mjs\` from \`results/runs.jsonl\` and`);
P(`\`results/infra-failures.jsonl\`. Nothing here is hand-entered.`);
P();
P(`- repo: **${REPO}** @ \`${(runs[0]?.repoSha || questions.sha || "").slice(0, 10)}\``);
P(`- model: ${[...new Set(runs.map((r) => r.model))].join(", ") || "-"}`);
P(`- isolation mode: ${[...new Set(runs.map((r) => r.isolation))].join(", ") || "-"}`);
P(`- per-run cap: $${[...new Set(runs.map((r) => r.maxBudgetUsd))].join(", ") || "-"}`);
P(`- cells recorded: **${expected.length - missing.length} / ${expected.length}**`);
P(`- total recorded spend: **$${fmt(runs.reduce((s, r) => s + (r.costUsd || 0), 0), 2)}**`);
P();
if (missing.length) {
  const shown = missing.slice(0, 12).map((m) => m.replace(/\|/g, "/")).join(", ");
  P(`> **INCOMPLETE.** ${missing.length} cell(s) not yet recorded: ${shown}` +
    `${missing.length > 12 ? ` ... and ${missing.length - 12} more` : ""}.`);
  P(`> The harness is resumable - re-invoking it runs exactly these.`);
  P();
}
if (dupes.length) { P(`> **DUPLICATE ROWS** for: ${[...new Set(dupes)].join(", ")}`); P(); }

// ---- per-arm ----------------------------------------------------------------
P(`## Per arm`);
P();
P(`| Arm | n | censored | censoring rate | median cost | median turns | median duration s | median executed calls | median mcp share |`);
P(`|---|---|---|---|---|---|---|---|---|`);
const armStats = {};
for (const a of ARMS) {
  const rs = runs.filter((r) => r.arm === a);
  const cens = rs.filter((r) => r.censored).length;
  const st = {
    n: rs.length,
    cens,
    rate: rs.length ? cens / rs.length : null,
    cost: median(rs.map((r) => r.costUsd)),
    turns: median(rs.map((r) => r.numTurns)),
    dur: median(rs.map((r) => (r.durationMs == null ? null : r.durationMs / 1000))),
    calls: median(rs.map((r) => (r.toolCallsExecuted || []).length)),
    share: median(rs.map(mcpShare).filter((x) => x != null)),
  };
  armStats[a] = st;
  P(`| ${a} | ${st.n} | ${st.cens} | ${st.rate == null ? "-" : (st.rate * 100).toFixed(1) + "%"} | $${fmt(st.cost)} | ${fmt(st.turns, 1)} | ${fmt(st.dur, 1)} | ${fmt(st.calls, 1)} | ${st.share == null ? "-" : st.share.toFixed(2)} |`);
}
P();
// DESIGN 6.6: if censoring rates differ by more than 10 points between arms the medians are not
// comparable and the write-up has to say so. Stated here rather than left for a reader to notice.
const rates = ARMS.map((a) => armStats[a].rate).filter((x) => x != null);
if (rates.length === ARMS.length) {
  const spread = (Math.max(...rates) - Math.min(...rates)) * 100;
  P(`Censoring-rate spread across arms: **${spread.toFixed(1)} points** ` +
    `(DESIGN 6.6 threshold: >10 points means the medians are NOT comparable and the write-up must say so). ` +
    `**${spread > 10 ? "OVER the threshold" : "Within the threshold"}.**`);
  P();
}

// ---- per question x arm -----------------------------------------------------
P(`## Per question x arm (median over reps)`);
P();
P(`| Question | Class | G cost | M cost | B cost | G turns | M turns | B turns |`);
P(`|---|---|---|---|---|---|---|---|`);
for (const q of QIDS) {
  const c = (a, f) => median(runs.filter((r) => r.questionId === q && r.arm === a).map(f));
  P(`| ${q} | ${CLASS_OF[q]} | $${fmt(c("G", (r) => r.costUsd))} | $${fmt(c("M", (r) => r.costUsd))} | $${fmt(c("B", (r) => r.costUsd))} | ` +
    `${fmt(c("G", (r) => r.numTurns), 1)} | ${fmt(c("M", (r) => r.numTurns), 1)} | ${fmt(c("B", (r) => r.numTurns), 1)} |`);
}
P();

// ---- the four pilot questions from DESIGN section 10 ------------------------
P(`## The four numbers the pilot exists to produce (DESIGN section 10)`);
P();

// 1. manipulation check
const shareM = armStats.M.share, shareB = armStats.B.share;
P(`**1. Does \`mcp_call_share\` clear 0.2?**`);
P();
P(`| Arm | median mcp share | runs below 0.2 | verdict |`);
P(`|---|---|---|---|`);
for (const a of ["M", "B"]) {
  const rs = runs.filter((r) => r.arm === a);
  const shares = rs.map(mcpShare).filter((x) => x != null);
  const below = shares.filter((x) => x < 0.2).length;
  const med = median(shares);
  P(`| ${a} | ${med == null ? "-" : med.toFixed(2)} | ${below}/${shares.length} | ${med == null ? "-" : (med >= 0.2 ? "clears" : "**BELOW 0.2 - the manipulation did not take**")} |`);
}
const gShares = runs.filter((r) => r.arm === "G").map(mcpShare).filter((x) => x != null);
P();
P(`Arm G median mcp share: ${median(gShares) == null ? "-" : median(gShares).toFixed(2)} (must be 0 by construction).`);
P();
// Where arm B's share goes is the whole story of the manipulation check, and a single median hides
// it: the effect is per QUESTION, not spread evenly, and it repeats across reps.
P(`Arm B, per question - the manipulation check is not uniform, so the median above hides it.`);
P(`\`mcp offered\` is the count of devcontext tools present at init: it is the proof that a run with`);
P(`zero mcp calls CHOSE not to call them rather than being unable to.`);
P();
P(`| Question | Class | reps with 0 mcp calls | median mcp calls | median file calls | median mcp share | mcp offered at init |`);
P(`|---|---|---|---|---|---|---|`);
for (const q of QIDS) {
  const rs = runs.filter((r) => r.questionId === q && r.arm === "B");
  const mcpN = (r) => (r.toolCallsExecuted || []).filter((c) => String(c).startsWith("mcp__")).length;
  const fileN = (r) => (r.toolCallsExecuted || []).filter((c) => ["Read", "Grep", "Glob"].includes(String(c))).length;
  const zero = rs.filter((r) => mcpN(r) === 0).length;
  // mcpToolsOffered is a COUNT, and mcpServers carries the connection status. Both are stated so a
  // zero-mcp run cannot be explained away as "the server was not up".
  const offered = [...new Set(rs.map((r) => `${r.mcpToolsOffered} tools, ${(r.mcpServers || []).map((s) => `${s.name}:${s.status}`).join(" ")}`))].join(" / ");
  const sh = median(rs.map(mcpShare).filter((x) => x != null));
  P(`| ${q} | ${CLASS_OF[q]} | **${zero}/${rs.length}** | ${fmt(median(rs.map(mcpN)), 1)} | ${fmt(median(rs.map(fileN)), 1)} | ` +
    `${sh == null ? "-" : sh.toFixed(2)} | ${offered} |`);
}
P();

// 2. cost populated
const nullCost = runs.filter((r) => r.costUsd == null || r.costUsd === 0);
P(`**2. Does \`total_cost_usd\` populate?** ${nullCost.length === 0 ? `Yes - all ${runs.length} rows carry a non-zero cost.` : `**NO - ${nullCost.length} row(s) have null or zero cost:** ${nullCost.map((r) => `${r.questionId}/${r.arm}/rep${r.rep}`).join(", ")}`}`);
P();

// 3. isolation
const breaches = runs.filter((r) => r.isolationOk !== true);
P(`**3. Do the arm-isolation assertions hold?** ${breaches.length === 0 ? `Yes - \`isolationOk\` is true on all ${runs.length} rows, and \`verify.mjs\` re-derives DESIGN section 8 assertions 1-4 from the transcripts independently (\`audit-preflight.mjs\`).` : `**NO - ${breaches.length} breach(es):** ${breaches.map((r) => `${r.questionId}/${r.arm}/rep${r.rep}`).join(", ")}. Every number collected under this harness is void.`}`);
P();

// 4. between-rep variance vs the 20% effect the full run must resolve
P(`**4. Is between-rep variance small enough for n=5 to resolve a 20% effect?**`);
P();
P(`Per (question x arm) cell, the spread of cost across its reps, as a coefficient of variation`);
P(`(sd/mean, n-1 denominator). The decision rule in DESIGN section 5 turns on a 20% cost`);
P(`difference, i.e. \`log2(ratio) < -0.32\`.`);
P();
P(`| Arm | median CV across cells | max CV | cells with CV > 0.20 |`);
P(`|---|---|---|---|`);
const allCv = [];
for (const a of ARMS) {
  const cvs = [];
  for (const q of QIDS) {
    const cs = runs.filter((r) => r.questionId === q && r.arm === a && !r.censored).map((r) => r.costUsd).filter((x) => typeof x === "number");
    if (cs.length < 2) continue;
    const mean = cs.reduce((s, x) => s + x, 0) / cs.length;
    const sd = Math.sqrt(cs.reduce((s, x) => s + (x - mean) ** 2, 0) / (cs.length - 1));
    if (mean > 0) cvs.push(sd / mean);
  }
  allCv.push(...cvs);
  P(`| ${a} | ${cvs.length ? median(cvs).toFixed(3) : "-"} | ${cvs.length ? Math.max(...cvs).toFixed(3) : "-"} | ${cvs.filter((x) => x > 0.2).length}/${cvs.length} |`);
}
P();
if (allCv.length) {
  // Standard error of a mean of n reps is cv/sqrt(n). Reported as an order-of-magnitude read on
  // whether n=5 can see a 20% difference at all - it is NOT the pre-registered analysis, which is
  // a bootstrap over questions (DESIGN section 9) and belongs to A1.2.
  const mcv = median(allCv);
  P(`Median CV across all cells: **${mcv.toFixed(3)}**. At n=5 reps the standard error of a cell mean is`);
  P(`cv/sqrt(5) = **${(mcv / Math.sqrt(5)).toFixed(3)}**, against the 0.20 effect the decision rule must resolve.`);
  P(`This is a rough read only - the pre-registered analysis is a bootstrap over questions (DESIGN section 9), not this.`);
}
P();

// ---- infrastructure ---------------------------------------------------------
P(`## Infrastructure attempts quarantined (not data)`);
P();
if (!infra.length) {
  P(`None. Every spawned subprocess returned a classifiable run.`);
} else {
  P(`${infra.length} attempt(s) were classified as infrastructure interruptions - an API error status,`);
  P(`a dead subprocess or a missing result event - and were therefore NOT written to \`runs.jsonl\`.`);
  P(`They are kept in \`results/infra-failures.jsonl\` and \`results/infra/\`, and the affected cells were`);
  P(`re-run. This is not censoring: DESIGN 6.6 censoring is a run that ran and hit its own cap.`);
  P();
  P(`| Question | Arm | Rep | Attempt | subtype | terminal reason | api status | exit | wall ms | $ burnt |`);
  P(`|---|---|---|---|---|---|---|---|---|---|`);
  for (const r of infra) {
    P(`| ${r.questionId} | ${r.arm} | ${r.rep} | ${r.attempt} | ${r.subtype ?? "-"} | ${r.terminalReason ?? "-"} | ` +
      `${r.apiErrorStatus ?? "-"} | ${r.exitCode ?? "-"} | ${r.wallMs ?? "-"} | $${fmt(r.costUsd, 4)} |`);
  }
  P();
  const byArm = ARMS.map((a) => `${a}=${infra.filter((r) => r.arm === a).length}`).join(" ");
  const burnt = infra.reduce((s, r) => s + (r.costUsd || 0), 0);
  P(`Per arm: ${byArm}. Rows in \`runs.jsonl\` whose \`attempt\` field is >1 are the successful re-runs.`);
  P();
  P(`**$${fmt(burnt, 2)} was spent on these attempts and is NOT in the recorded spend above**, because the`);
  P(`attempts are not runs. Total money the pilot actually cost = recorded + quarantined =`);
  P(`**$${fmt(runs.reduce((s, r) => s + (r.costUsd || 0), 0) + burnt, 2)}**. DESIGN section 10 asks for actual spend, not estimated.`);
  P();
  P(`Note for anyone writing classification code later: \`subtype\` is not a reliable success signal from`);
  P(`this CLI. The first interruption of this pilot reported \`subtype: "success"\` with \`is_error: true\`,`);
  P(`\`terminal_reason: "api_error"\` and the answer text "API Error: Connection lost mid-response".`);
  P(`Read \`is_error\` and \`terminal_reason\` too.`);
}
P();

// ---- provenance -------------------------------------------------------------
P(`## Provenance`);
P();
P(`- seed: \`20260811\` (question order randomised, arms interleaved not blocked - DESIGN 6.5).`);
P(`  The planned order is reproducible: \`node eval/agent-probe/run-probe.mjs --repo ${REPO} --reps 3 --allow-no-bare --dry-run\`.`);
P(`- retried cells (attempt > 1): ${runs.filter((r) => (r.attempt || 1) > 1).map((r) => `${r.questionId}/${r.arm}/rep${r.rep}`).join(", ") || "none"}`);
P(`- runs recorded from earlier stages and reused rather than re-run: ${runs.filter((r) => r.attempt == null).length} (H1.2 smoke rows; same harness, same argv, same cap).`);
P(`- raw transcript + result JSON for every row is under \`results/raw/${REPO}/\`.`);
P();

writeFileSync(OUT, L.join("\n") + "\n", "utf8");
console.log(`wrote ${OUT}`);
console.log(`cells ${expected.length - missing.length}/${expected.length}, missing ${missing.length}, infra attempts ${infra.length}`);
if (missing.length) process.exitCode = 0; // incomplete is a reportable state, not a script failure
